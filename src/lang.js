/* Две стороны карточки: язык изучения и язык перевода.

   В базе запись всегда лежит по-английски (`en`, `exEn`), а `tr` и `exTr` —
   карты переводов по языкам. Английский тут опорный: через него связаны все
   остальные языки, и любой из них — это перевод английской строки. Поэтому
   пара «изучаю → перевод» читается из одной записи: лицевая сторона берётся
   на языке изучения, оборот — на языке перевода.

   Английский — особый случай. Как язык изучения это само слово, как язык
   перевода — толкование из пакета `en` (та самая пара English → English);
   толкования нет — показываем слово, оно всё равно понятнее прочерка. */

/** Слово на языке `lang` — лицевая сторона карточки. */
export function word(item, lang) {
  return (lang === "en" ? item.en : item.tr?.[lang]) || "";
}

/** Перевод или толкование на языке `lang` — оборот карточки. */
export function meaning(item, lang) {
  return (lang === "en" ? item.tr?.en || item.en : item.tr?.[lang]) || "";
}

/** Пример на языке `lang`: на английском он свой, на остальных — перевод. */
export function example(item, lang) {
  return (lang === "en" ? item.exEn : item.exTr?.[lang]) || "";
}

/** Пометка происхождения для пары: машинной считается карточка, у которой
    машинная хотя бы одна сторона. */
export function origin(item, { study, lang }) {
  const marks = [study, lang].map((code) => (code === "en" ? "ok" : item.src?.[code]));
  return marks.includes("mt") ? "mt" : "ok";
}

/** Годится ли запись для выбранной пары: без слова или без перевода карточка
    показала бы прочерк и ничему не научила. */
export function usable(item, { study, lang }) {
  return !!word(item, study) && !!meaning(item, lang);
}
